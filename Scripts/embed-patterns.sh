#!/bin/sh
# Writes Sources/TribrachWire/PatternsData.swift from the vendored copy of
# core's tests/conformance/patterns.json. Run after updating Tests/TribrachCoreTests/core.
set -e
cd "$(dirname "$0")/.."
src=Tests/TribrachCoreTests/core/patterns.json
out=Sources/TribrachWire/PatternsData.swift
{
  echo "// Generated by Scripts/embed-patterns.sh from core's tests/conformance/patterns.json. Do not edit."
  echo ""
  echo "let patternsJSON = #\"\"\""
  cat "$src"
  echo "\"\"\"#"
} > "$out"
