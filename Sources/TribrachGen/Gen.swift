import Foundation
import TribrachWire

/// Writes Swift DTOs, decoders and encoders from the JSON Schemas that
/// core exports (Tribrach.Schema). It understands the subset core emits and
/// refuses anything else rather than guess:
///
/// - closed objects of scalar fields, required or optional;
/// - tagged unions: oneOf objects told apart by a constant field;
/// - booleans, bounded integers (with multipleOf), strings with lengths and
///   one of core's named patterns, enums;
/// - whole numbers as decimal strings (bounds under x-tribrach), which
///   become Int64;
/// - RFC 3339 instants, which become Date.
///
/// The generated code calls TribrachWire, which reads JSON the way core's
/// Lean decoders do.
public enum Gen {
    public struct Spec {
        public let name: String  // Swift type name, such as StartRequest
        public let source: String  // where the schema came from, for the header
        public let schema: Data

        public init(name: String, source: String, schema: Data) {
            self.name = name
            self.source = source
            self.schema = schema
        }
    }

    public struct Failure: Error, CustomStringConvertible {
        public let description: String
        init(_ d: String) { description = d }
    }

    public static func generate(_ specs: [Spec]) throws -> String {
        var g = Writer()
        g.line("// Code generated by tribrach-swift gen; DO NOT EDIT.")
        g.line("//")
        g.line("// Sources:")
        for s in specs { g.line("//   - \(s.source)") }
        g.line("")
        g.line("import Foundation")
        g.line("import TribrachWire")
        for s in specs {
            let sc: WireValue
            do { sc = try WireValue.parse(s.schema) } catch { throw Failure("\(s.source): \(error)") }
            guard case let .object(o) = sc else { throw Failure("\(s.source): a schema must be an object") }
            do { try g.top(s.name, o) } catch let f as Failure { throw Failure("\(s.source): \(f.description)") }
        }
        return g.out
    }

    /// An exported Swift name: `ev-charging` becomes `EvCharging`.
    public static func typeName(_ s: String) -> String {
        var out = ""
        var up = true
        for c in s {
            if c == "-" || c == "_" || c == "." { up = true; continue }
            out += up ? c.uppercased() : String(c)
            up = false
        }
        return out
    }

    static let keywords: Set<String> = [
        "associatedtype", "class", "deinit", "enum", "extension", "func", "import", "init", "inout", "internal",
        "let", "operator", "private", "protocol", "public", "static", "struct", "subscript", "typealias", "var",
        "break", "case", "continue", "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in",
        "repeat", "return", "switch", "where", "while", "as", "catch", "false", "is", "nil", "rethrows", "super",
        "self", "Self", "throw", "throws", "true", "try", "Type", "Any", "any", "some",
    ]

    /// A Swift property or case name: `ev-charging` becomes `evCharging`.
    public static func memberName(_ s: String) -> String {
        let t = typeName(s)
        let n = t.prefix(1).lowercased() + t.dropFirst()
        return keywords.contains(n) ? "`\(n)`" : n
    }

    static func bare(_ n: String) -> String { n.trimmingCharacters(in: CharacterSet(charactersIn: "`")) }

    static func quote(_ s: String) -> String {
        var out = "\""
        for u in s.unicodeScalars {
            switch u {
            case "\\": out += "\\\\"
            case "\"": out += "\\\""
            case "\n": out += "\\n"
            default:
                if u.value < 0x20 || u.value == 0x7f { out += "\\u{\(String(u.value, radix: 16))}" } else { out.unicodeScalars.append(u) }
            }
        }
        return out + "\""
    }
}

/// How one field reads and writes.
struct Scalar {
    let type: String
    let doc: String
    let read: (_ v: String, _ path: String) -> String
    let write: (_ v: String) -> String
}

struct Field {
    let json: String
    let name: String
    let scalar: Scalar
    let required: Bool
    var type: String { required ? scalar.type : scalar.type + "?" }
}

struct Writer {
    var out = ""
    var indent = 0

    mutating func line(_ s: String) {
        out += s.isEmpty ? "\n" : String(repeating: "    ", count: indent) + s + "\n"
    }

    mutating func doc(_ text: String) {
        for l in text.split(separator: "\n", omittingEmptySubsequences: false) { line("/// \(l)") }
    }

    mutating func top(_ name: String, _ sc: [String: WireValue]) throws {
        let id = sc["$id"]?.stringValue ?? ""
        let title = sc["title"]?.stringValue ?? name
        line("")
        if case let .array(alts)? = sc["oneOf"] {
            try union(name, title, id, alts)
        } else if sc["type"] == .string("object") {
            try object(name, title, id, sc, tag: nil)
        } else {
            throw Gen.Failure("the top level must be an object or a tagged union")
        }
    }

    mutating func entryPoints(_ name: String, _ title: String, _ id: String) {
        line("public static let schema = \(Gen.quote(id))")
        line("")
        line("/// Reads a \(title), rejecting anything its schema rejects.")
        line("public static func decode(_ data: Data) throws -> \(name) {")
        line("    let r = WireReader(schema: schema)")
        line("    return try read(r, r.parse(data), \"\")")
        line("}")
        line("")
        line("/// Writes a \(title). It throws rather than write JSON its own schema")
        line("/// would reject.")
        line("public func encode() throws -> Data {")
        line("    let data = write().data")
        line("    _ = try \(name).decode(data)")
        line("    return data")
        line("}")
    }

    func fields(_ owner: String, _ sc: [String: WireValue], tag: String?) throws -> [Field] {
        guard sc["additionalProperties"] == .bool(false) else {
            throw Gen.Failure("\(owner): objects must be closed (additionalProperties: false)")
        }
        guard case let .object(props)? = sc["properties"] else { return [] }
        var names: [String] = []
        if case let .array(req)? = sc["required"] {
            names = req.compactMap(\.stringValue)
        }
        let required = Set(names)
        names += props.keys.filter { !required.contains($0) }.sorted()
        var out: [Field] = []
        for n in names where n != tag {
            guard case let .object(ps)? = props[n] else { throw Gen.Failure("\(owner).\(n): no schema for a required field") }
            let s: Scalar
            do { s = try scalar(ps) } catch let f as Gen.Failure { throw Gen.Failure("\(owner).\(n): \(f.description)") }
            out.append(Field(json: n, name: Gen.memberName(n), scalar: s, required: required.contains(n)))
        }
        return out
    }

    mutating func object(_ name: String, _ title: String, _ id: String, _ sc: [String: WireValue], tag: String?) throws {
        let fs = try fields(name, sc, tag: tag)
        var keys = fs.map(\.json)
        if let tag { keys.insert(tag, at: 0) }
        doc("A \(title).")
        if !id.isEmpty { doc("Schema: \(id)") }
        line("public struct \(name): Equatable, Sendable {")
        indent += 1
        for f in fs {
            if !f.scalar.doc.isEmpty { doc(f.scalar.doc) }
            line("public var \(f.name): \(f.type)")
        }
        line("")
        let params = fs.map { "\($0.name): \($0.type)\($0.required ? "" : " = nil")" }.joined(separator: ", ")
        line("public init(\(params)) {")
        for f in fs { line("    self.\(Gen.bare(f.name)) = \(f.name)") }
        line("}")
        if tag == nil {
            line("")
            entryPoints(name, title, id)
        }
        line("")
        line("static func read(_ r: WireReader, _ v: WireValue, _ path: String) throws -> \(name) {")
        line("    let m = try r.object(v, path, [\(keys.map(Gen.quote).joined(separator: ", "))])")
        if fs.isEmpty {
            line("    _ = m")
            line("    return \(name)()")
        } else {
            line("    return try \(name)(")
            for (i, f) in fs.enumerated() {
                let p = "WireReader.join(path, \(Gen.quote(f.json)))"
                let expr = f.required
                    ? f.scalar.read("r.field(m, path, \(Gen.quote(f.json)))", p)
                    : "m[\(Gen.quote(f.json))].map { v in try \(f.scalar.read("v", p)) }"
                line("        \(Gen.bare(f.name)): \(expr)\(i == fs.count - 1 ? "" : ",")")
            }
            line("    )")
        }
        line("}")
        line("")
        line("func fields() -> [String: WireValue] {")
        line("    var m: [String: WireValue] = [:]")
        for f in fs {
            if f.required {
                line("    m[\(Gen.quote(f.json))] = \(f.scalar.write(f.name))")
            } else {
                line("    if let x = \(f.name) { m[\(Gen.quote(f.json))] = \(f.scalar.write("x")) }")
            }
        }
        line("    return m")
        line("}")
        line("")
        line("func write() -> WireValue { .object(fields()) }")
        indent -= 1
        line("}")
    }

    mutating func union(_ name: String, _ title: String, _ id: String, _ alts: [WireValue]) throws {
        var tag: String?
        var cases: [(String, [String: WireValue])] = []
        for a in alts {
            guard case let .object(o) = a, o["type"] == .string("object") else {
                throw Gen.Failure("\(name): oneOf alternatives must be objects")
            }
            var found: (String, String)?
            if case let .object(props)? = o["properties"] {
                for k in props.keys.sorted() {
                    if case let .object(p)? = props[k], case let .string(c)? = p["const"] {
                        if found != nil { throw Gen.Failure("\(name): an alternative has two constant fields") }
                        found = (k, c)
                    }
                }
            }
            guard case let (k, c)? = found, tag == nil || tag == k else {
                throw Gen.Failure("\(name): alternatives must share one constant tag field")
            }
            guard !cases.contains(where: { $0.0 == c }) else { throw Gen.Failure("\(name): two alternatives share the tag \"\(c)\"") }
            tag = k
            cases.append((c, o))
        }
        guard let tag else { throw Gen.Failure("\(name): a union needs alternatives") }
        doc("A \(title): told apart on the wire by \"\(tag)\".")
        doc("Schema: \(id)")
        line("public enum \(name): Equatable, Sendable {")
        indent += 1
        for (c, _) in cases { line("case \(Gen.memberName(c))(\(Gen.typeName(c)))") }
        line("")
        entryPoints(name, title, id)
        line("")
        line("static func read(_ r: WireReader, _ v: WireValue, _ path: String) throws -> \(name) {")
        line("    switch try r.tag(v, path, \(Gen.quote(tag)), [\(cases.map { Gen.quote($0.0) }.joined(separator: ", "))]) {")
        for (c, _) in cases {
            line("    case \(Gen.quote(c)): return try .\(Gen.memberName(c))(\(Gen.typeName(c)).read(r, v, path))")
        }
        line("    default: throw WireError(schema: r.schema, path: path, reason: \"unknown case\")")
        line("    }")
        line("}")
        line("")
        line("func write() -> WireValue {")
        line("    var m: [String: WireValue]")
        line("    switch self {")
        for (c, _) in cases {
            line("    case let .\(Gen.memberName(c))(x): m = x.fields(); m[\(Gen.quote(tag))] = .string(\(Gen.quote(c)))")
        }
        line("    }")
        line("    return .object(m)")
        line("}")
        for (c, o) in cases {
            line("")
            try object(Gen.typeName(c), "\(title), case \"\(c)\"", "", o, tag: tag)
        }
        indent -= 1
        line("}")
    }

    static let known: Set<String> = [
        "type", "description", "minimum", "maximum", "multipleOf", "minLength", "maxLength", "pattern", "format",
        "enum", "x-tribrach",
    ]

    func scalar(_ ps: [String: WireValue]) throws -> Scalar {
        for k in ps.keys.sorted() where !Writer.known.contains(k) {
            throw Gen.Failure("unsupported keyword \"\(k)\"")
        }
        let doc = ps["description"]?.stringValue ?? ""
        func num(_ v: WireValue?) -> String? {
            guard case let .number(t)? = v, let n = Int64(t) else { return nil }
            return String(n)
        }
        func args(_ pairs: [(String, String?)]) -> String {
            pairs.compactMap { k, v in v.map { ", \(k): \($0)" } }.joined()
        }
        if case let .array(vals)? = ps["enum"] {
            let qs = try vals.map { v -> String in
                guard case let .string(s) = v else { throw Gen.Failure("only string enums are supported") }
                return Gen.quote(s)
            }
            return Scalar(type: "String", doc: doc, read: { "r.oneOf(\($0), \($1), [\(qs.joined(separator: ", "))])" }, write: { ".string(\($0))" })
        }
        switch ps["type"]?.stringValue {
        case "boolean":
            return Scalar(type: "Bool", doc: doc, read: { "r.bool(\($0), \($1))" }, write: { ".bool(\($0))" })
        case "integer":
            let a = args([("min", num(ps["minimum"])), ("max", num(ps["maximum"])), ("multipleOf", num(ps["multipleOf"]))])
            return Scalar(type: "Int64", doc: doc, read: { "r.int(\($0), \($1)\(a))" }, write: { "WireWrite.int(\($0))" })
        case "string":
            let regex = ps["pattern"]?.stringValue
            if regex == nil, ps["format"] != nil { throw Gen.Failure("a format without a pattern isn't checkable") }
            var pat: WirePattern?
            if let regex {
                guard let p = WirePattern.byRegex(regex) else {
                    throw Gen.Failure("TRS0403 unknown pattern \(Gen.quote(regex)): core's patterns (Tribrach.Schema.Pat) are a closed list; fix: update tribrach-swift to the core version that exported this schema")
                }
                pat = p
            }
            var x: [String: WireValue]?
            if case let .object(o)? = ps["x-tribrach"] { x = o }
            switch pat?.name {
            case "decimal":
                let a = args([("min", num(x?["minimum"])), ("max", num(x?["maximum"]))])
                return Scalar(type: "Int64", doc: doc, read: { "r.decimal(\($0), \($1)\(a))" }, write: { "WireWrite.decimal(\($0))" })
            case "instant":
                if ps["minLength"] != nil || ps["maxLength"] != nil { throw Gen.Failure("lengths on an instant aren't supported") }
                return Scalar(type: "Date", doc: doc, read: { "r.instant(\($0), \($1))" }, write: { "WireWrite.instant(\($0))" })
            default:
                break
            }
            if x != nil { throw Gen.Failure("x-tribrach bounds only apply to decimal strings") }
            let a = args([("minLength", num(ps["minLength"])), ("maxLength", num(ps["maxLength"])), ("pattern", pat.map { Gen.quote($0.name) })])
            return Scalar(type: "String", doc: doc, read: { "r.string(\($0), \($1)\(a))" }, write: { ".string(\($0))" })
        default:
            throw Gen.Failure("unsupported field schema (arrays and nested objects come later)")
        }
    }
}

extension WireValue {
    var stringValue: String? { if case let .string(s) = self { return s } else { return nil } }
}
